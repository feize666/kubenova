export function searchHandbook(query: string): HandbookChapter[] {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return handbookChapters;
  return handbookChapters.filter(chapter => {
    const text = [chapter.title, chapter.summary, chapter.permission,
      ...chapter.topics.flatMap(topic => [topic.title, ...topic.steps, topic.note ?? ""]),
    ].join(" ").toLocaleLowerCase();
    return terms.every(term => text.includes(term));
  });
}
