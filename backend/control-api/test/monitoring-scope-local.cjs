const assert = require('node:assert/strict');
const { PrismaClient } = require('@prisma/client');
const load = name => require(`../dist/src/${name}`);
const { MonitoringService } = load('monitoring/monitoring.service');
const { AiopsService } = load('aiops/aiops.service');
const { AiopsController } = load('aiops/aiops.controller');
const { AuthorizationService } = load('common/authorization.service');
const { ClusterAccessService } = load('common/cluster-access.service');
const { NamespaceIdentityService } = load('common/namespace-identity.service');
const { ClustersService } = load('clusters/clusters.service');
const { K8sClientService } = load('clusters/k8s-client.service');
const { LiveMetricsService } = load('metrics/live-metrics.service');
const url = new URL(process.env.DATABASE_URL || 'postgresql://invalid');
assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(url.hostname), 'Explicit local DB required');
const db = new PrismaClient();
(async () => {
  const actor = await db.user.findFirst({ where: { email: 'loop-read', isActive: true }, select: { id: true, role: true } });
  assert.ok(actor);
  const authorization = new AuthorizationService(db);
  const access = new ClusterAccessService(db, authorization);
  const clients = new K8sClientService();
  const clusters = new ClustersService(db, clients);
  const identity = new NamespaceIdentityService(clusters, clients);
  const grants = await authorization.listEffectiveGrants(actor.id);
  assert.equal(grants.length, 1);
  assert.deepEqual(grants[0].namespaces.map(row => row.namespaceName), ['ai']);
  const clusterId = grants[0].clusterId;
  const service = new MonitoringService(db, clusters, new LiveMetricsService(clients), undefined, access, authorization, identity);
  for (const requestedCluster of [undefined, clusterId]) {
    const result = await service.getAlerts({ clusterId: requestedCluster, range: '7d', pageSize: 100 }, actor);
    assert.ok(result.items.every(row => row.clusterId === clusterId && row.namespace === 'ai' && row.resourceType !== 'Secret'), 'alerts must stay in authorized namespace');
  }
  await assert.rejects(service.getAlerts({ clusterId: 'unauthorized-cluster' }, actor), error => error.getStatus?.() === 403);
  const overview = await service.getOverview({ clusterId, range: '7d' }, actor);
  for (const key of ['healthScore', 'clusterHealthy', 'cpuUsagePercent', 'memoryUsagePercent']) assert.equal(overview[key], null, key);
  assert.equal(overview.liveSnapshot, undefined);
  const inspection = await service.getClusterInspection(clusterId, undefined, { range: '7d' }, actor);
  assert.ok(inspection.items.every(row => row.clusterId === clusterId && row.namespace === 'ai' && row.resourceKind !== 'Secret'));
  const alertExport = JSON.parse((await service.exportAlerts({ clusterId, range: '7d' }, 'json', actor)).data);
  assert.ok(alertExport.items.every(row => row.clusterId === clusterId && row.namespace === 'ai' && row.resourceType !== 'Secret'));
  const inspectionExport = JSON.parse((await service.exportClusterInspectionReport(clusterId, undefined, 'json', { range: '7d' }, actor)).data);
  assert.ok(inspectionExport.items.every(row => row.clusterId === clusterId && row.namespace === 'ai' && row.resourceKind !== 'Secret'));
  const summary = await service.getObservabilitySummary({ clusterId, range: '7d' }, actor);
  assert.equal(summary.healthScore, null);
  assert.ok(summary.externalLinks.every(row => !row.available && !row.url));
  await assert.rejects(service.getGrafanaPanelConfiguration(clusterId, '7d', actor), error => error.getStatus?.() === 403);
  const aiops = new AiopsService(service, authorization, access, identity);
  const aiController = new AiopsController(aiops);
  const ai = await aiController.getSummary('7d', undefined, undefined, clusterId, { user: { user: actor } });
  const inspectionIds = new Set(inspection.items.map(row => `inspection:${row.id}`));
  assert.ok(ai.incidentQueue.every(row => row.id.startsWith('inspection:') ? inspectionIds.has(row.id) : row.affectedScope.startsWith(`${clusterId}/ai/`)));
  await assert.rejects(aiController.precheckRecommendation({ user: { user: actor } }, { recommendationId: 'rec:alert:forged' }), error => error.getStatus?.() === 403);
  console.log('PASS real scoped monitoring alerts/inspection/summary/AIOps, unavailable global metrics, foreign-cluster and Grafana denial; no writes or sessions');
})().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(() => db.$disconnect());
