const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { createServer } = require('node:http');
const { once } = require('node:events');
const { PrismaClient } = require('@prisma/client');
const { NotificationWorker } = require('../dist/src/monitoring/notification-worker');
const { ObservabilityService } = require('../dist/src/monitoring/observability.service');
const url = new URL(process.env.DATABASE_URL || 'postgresql://invalid');
if (!['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) throw new Error('Loopback DB required');
const db = new PrismaClient();
let cluster;
let statusCode = 200;
const requests = [];
const server = createServer(async (req, res) => {
  let body = '';
  for await (const chunk of req) body += chunk;
  requests.push(JSON.parse(body));
  res.writeHead(statusCode, { 'content-type': 'application/json' });
  res.end('{}');
});
(async () => {
  try {
    server.listen(0, '127.0.0.1');
    await once(server, 'listening');
    const endpoint = `http://127.0.0.1:${server.address().port}`;
    cluster = await db.clusterRegistry.create({ data: { name: `worker-${randomUUID()}`, apiServer: 'https://invalid.test' } });
    const template = await db.monitoringNotificationTemplate.create({ data: { clusterId: cluster.id, name: 'test', channel: 'webhook', endpoint, bodyTemplate: '{"title":"{{title}}","message":"{{message}}"}' } });
    const alert = await db.monitoringAlert.create({ data: { clusterId: cluster.id, severity: 'warning', title: 'Test', message: 'Detail' } });
    const firing = await db.notificationDelivery.create({ data: { alertId: alert.id, templateId: template.id, event: 'firing', expiresAt: new Date(Date.now() + 60000) } });
    const worker = new NotificationWorker(db, new ObservabilityService(db));
    await Promise.all([worker.runOnce(cluster.id), worker.runOnce(cluster.id)]);
    assert.equal(requests.length, 1);
    assert.deepEqual(requests[0], { title: '告警：Test', message: 'Detail' });
    assert.equal((await db.notificationDelivery.findUnique({ where: { id: firing.id } })).status, 'sent');
    await db.monitoringAlert.update({ where: { id: alert.id }, data: { status: 'resolved' } });
    const recovery = await db.notificationDelivery.create({ data: { alertId: alert.id, templateId: template.id, event: 'resolved', expiresAt: new Date(Date.now() + 60000) } });
    statusCode = 503;
    await worker.runOnce(cluster.id);
    let row = await db.notificationDelivery.findUnique({ where: { id: recovery.id } });
    assert.equal(row.status, 'pending');
    assert.equal(row.attempts, 1);
    assert.ok(row.nextAttemptAt > new Date());
    assert.equal(await worker.runOnce(cluster.id), false, 'backoff must not be bypassed by database session timezone');
    assert.equal(requests.length, 2);
    statusCode = 200;
    await db.notificationDelivery.update({ where: { id: recovery.id }, data: { nextAttemptAt: new Date(0) } });
    await worker.runOnce(cluster.id);
    assert.equal(requests.length, 3);
    assert.deepEqual(requests[2], { title: '已恢复：Test', message: 'Detail' });
    assert.equal((await db.notificationDelivery.findUnique({ where: { id: recovery.id } })).status, 'sent');
    await db.notificationDelivery.update({ where: { id: recovery.id }, data: { status: 'sending', leaseUntil: new Date(0) } });
    await worker.runOnce(cluster.id);
    assert.equal(requests.length, 4, 'expired lease is reclaimed (at-least-once delivery)');
    await db.notificationDelivery.update({ where: { id: recovery.id }, data: { status: 'pending', nextAttemptAt: new Date(0), expiresAt: new Date(0) } });
    await worker.runOnce(cluster.id);
    assert.equal(requests.length, 4);
    assert.equal((await db.notificationDelivery.findUnique({ where: { id: recovery.id } })).status, 'expired');
    await db.notificationDelivery.update({ where: { id: recovery.id }, data: { status: 'pending', attempts: 0, nextAttemptAt: new Date(0), expiresAt: new Date(Date.now() + 60000) } });
    await db.monitoringNotificationTemplate.update({ where: { id: template.id }, data: { enabled: false } });
    await worker.runOnce(cluster.id);
    assert.equal(requests.length, 4);
    assert.equal((await db.notificationDelivery.findUnique({ where: { id: recovery.id } })).status, 'cancelled');
    await db.monitoringNotificationTemplate.update({ where: { id: template.id }, data: { enabled: true } });
    await db.notificationDelivery.update({ where: { id: firing.id }, data: { status: 'pending', attempts: 0, nextAttemptAt: new Date(Date.now() + 60000) } });
    await db.notificationDelivery.update({ where: { id: recovery.id }, data: { status: 'pending', attempts: 0, nextAttemptAt: new Date(0) } });
    await worker.runOnce(cluster.id);
    row = await db.notificationDelivery.findUnique({ where: { id: recovery.id } });
    assert.equal(row.status, 'pending', 'recovery waits for its firing');
    assert.equal(row.attempts, 0, 'waiting is not a send attempt');
    assert.equal(requests.length, 4);
    await db.notificationDelivery.update({ where: { id: firing.id }, data: { nextAttemptAt: new Date(0) } });
    await worker.runOnce(cluster.id);
    assert.equal((await db.notificationDelivery.findUnique({ where: { id: firing.id } })).status, 'cancelled', 'never-sent firing is obsolete after resolution');
    await db.notificationDelivery.update({ where: { id: recovery.id }, data: { nextAttemptAt: new Date(0) } });
    await worker.runOnce(cluster.id);
    assert.equal((await db.notificationDelivery.findUnique({ where: { id: recovery.id } })).status, 'cancelled');
    assert.equal(requests.length, 4, 'do not send unsolicited recovery');
    console.log('PASS real HTTP + PostgreSQL claim, concurrent suppression, firing/recovery payloads, 503 retry, lease recovery, expiry and disabled channel');
  } finally {
    if (cluster) { await db.monitoringAlert.deleteMany({ where: { clusterId: cluster.id } }); await db.clusterRegistry.delete({ where: { id: cluster.id } }); }
    await db.$disconnect();
    server.closeAllConnections();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(e => { console.error(e.message); process.exitCode = 1; });
